import { mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { dirname, resolve, relative } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const output = resolve(root, 'api/generated/progress-contracts');
const header = '// Generated by scripts/build-progress-api.mjs. Edit the source in src/lib/.\n';

/** Azure deploys api/ independently; keep its portable contracts identical to browser sources. */
export async function buildProgressApi({ check = false } = {}) {
  const files = new Map();
  const progressFiles = (await readdir(resolve(root, 'src/lib/progress')))
    .filter((name) => name.endsWith('.js'))
    .sort();
  for (const name of ['exercise-registry.js', ...progressFiles.map((name) => `progress/${name}`)]) {
    files.set(name, header + (await readFile(resolve(root, 'src/lib', name), 'utf8')));
  }
  const words = JSON.parse(await readFile(resolve(root, 'data/words.json'), 'utf8'));
  const itemIds = [...new Set(words.map(({ lv, en }) => `${lv}|${en || ''}`))];
  files.set('contexts.json', JSON.stringify({ 'darbibas-vards': { itemIds } }, null, 2) + '\n');
  files.set('package.json', JSON.stringify({ type: 'module' }, null, 2) + '\n');
  if (check) {
    const actualFiles = await readdir(output, { recursive: true, withFileTypes: true });
    const actualNames = actualFiles
      .filter((entry) => entry.isFile())
      .map((entry) => relative(output, resolve(entry.parentPath || entry.path, entry.name)));
    if (actualNames.length !== files.size || actualNames.some((name) => !files.has(name))) {
      throw new Error('Progress API artifacts are stale; run npm run build:progress-api');
    }
  } else await rm(output, { recursive: true, force: true });
  for (const [name, expected] of files) {
    const path = resolve(output, name);
    if (check) {
      if ((await readFile(path, 'utf8')) !== expected) {
        throw new Error(`Stale ${relative(root, path)}; run npm run build:progress-api`);
      }
    } else {
      await mkdir(dirname(path), { recursive: true });
      await writeFile(path, expected, 'utf8');
    }
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  buildProgressApi({ check: process.argv.includes('--check') }).catch((error) => {
    console.error(error.message);
    process.exitCode = 1;
  });
}
